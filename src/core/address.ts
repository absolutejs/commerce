export const supportedAddressCountries = Object.keys(requiredFields).filter(
  (code) => code !== "ZZ",
);
export const addressRequiredFields = (country: string) => {
  const code = country.trim().toUpperCase();
  const required = code === "ZZ" ? undefined : requiredFields[code];
  if (!required) return null;
  return {
    city: required.includes("C"),
    state: required.includes("S"),
    zip: required.includes("Z"),
  };
};
